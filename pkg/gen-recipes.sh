#!/bin/bash
# gen-recipes.sh: writes the two local PKGBUILDs from the AUR originals (kinect360, 2026-11-18).
# Re-runnable; the AUR originals in ../libfreenect and ../kinect-audio-setup are never edited.
set -euo pipefail
P=$(cd "$(dirname "$0")" && pwd)
S=$P/snippets; mkdir -p "$S" "$P/local/libfreenect" "$P/local/kinect-audio-setup"
cat > "$S/lf-udev" <<'EOF'
  install -Dm644 "${pkgname}-${pkgver}/platform/linux/udev/51-kinect.rules" "${pkgdir}/usr/lib/udev/rules.d/51-kinect.rules"
  sed -i 's/MODE="0666"/MODE="0660", GROUP="video", TAG+="uaccess"/' "${pkgdir}/usr/lib/udev/rules.d/51-kinect.rules"
EOF
cat > "$S/kas-udev" <<'EOF'
  sed -i 's/^ACTION=="add", SUBSYSTEMS=="usb", ATTRS{idVendor}=="045e", ATTRS{idProduct}=="02ad",/ACTION=="add", SUBSYSTEM=="usb", ENV{DEVTYPE}=="usb_device", ATTR{idVendor}=="045e", ATTR{idProduct}=="02ad",/' "${srcdir}/55-kinect-audio.rules"
  grep -q 'ENV{DEVTYPE}=="usb_device"' "${srcdir}/55-kinect-audio.rules"
EOF
emit() { # emit SRC DST NOTE SED-ARGS...
  local src=$1 dst=$2 note=$3; shift 3
  { echo "# Local variant of the AUR recipe, generated by $P/gen-recipes.sh from $src (kinect360, 2026-11-18)"; echo "# $note"; sed "$@" "$src"; } > "$dst.new"
  bash -n "$dst.new"; mv "$dst.new" "$dst"; echo "== $dst"; diff -u "$src" "$dst" | sed -n '3,999p' | grep -P '^[+-]' || true
}
emit "$P/libfreenect/PKGBUILD" "$P/local/libfreenect/PKGBUILD" "no python; no build-time fwfetcher; udev 0660 video + uaccess in /usr/lib" \
  -e 's/^pkgrel=1$/pkgrel=1.1/' \
  -e "s/'freeglut' 'python'/'freeglut'/" \
  -e "s/^makedepends=(.*)$/makedepends=('cmake' 'libxmu')/" \
  -e '/^optdepends=(/,/python demos.)$/d' \
  -e 's/-DBUILD_PYTHON3=ON/-DBUILD_PYTHON3=OFF/' \
  -e 's/-DBUILD_REDIST_PACKAGE=OFF/-DBUILD_REDIST_PACKAGE=ON/' \
  -e "\|platform/linux/udev/51-kinect.rules|{r $S/lf-udev" -e 'd}'
emit "$P/kinect-audio-setup/PKGBUILD" "$P/local/kinect-audio-setup/PKGBUILD" "source from Salsa (git.ao2.it stalls), commit = upstream tag v0.5; 7zip; udev rule fires once per usb_device" \
  -e 's/^pkgrel=4$/pkgrel=4.1/' \
  -e "s/'p7zip>=9.20'/'7zip'/" \
  -e 's|source=("git+${url}#tag=v${pkgver}"|source=("git+https://salsa.debian.org/debian/kinect-audio-setup.git#commit=4358ca108cb3393958f38b9366c70cf6b2aa1d0e"|' \
  -e "\|kinect_patch_udev_rules\" \"\$FIRMWARE_PATH\"|r $S/kas-udev"
